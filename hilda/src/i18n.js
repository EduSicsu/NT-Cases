export const DICT = { pt, en, ar }

export function makeT(lang) {
  const dict = DICT[lang] || pt
  const L = LANGS.find((l) => l.id === lang) || LANGS[0]
  const rules = new Intl.PluralRules(L.locale)
  const fill = (s, vars) =>
    vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`)) : s
  const t = (key, vars) => fill(dict[key] ?? pt[key] ?? key, vars)
  t.plural = (key, n, vars) => {
    const cat = rules.select(n)
    const s = dict[`${key}_${cat}`] ?? dict[`${key}_other`] ?? pt[`${key}_other`] ?? key
    return fill(s, { n, ...vars })
  }
  t.lang = lang
  t.dir = L.dir
  t.locale = L.locale
  const money = new Intl.NumberFormat(L.locale, { style: 'currency', currency: 'BRL' })
  t.money = (cents) => '\u2066' + money.format(cents / 100) + '\u2069'
  const num = new Intl.NumberFormat(L.locale, { maximumFractionDigits: 2 })
  t.num = (n) => num.format(n)
  const dayFmt = new Intl.DateTimeFormat(L.locale, { weekday: 'short', day: 'numeric', month: 'short' })
  t.day = (d) => dayFmt.format(d)
  const timeFmt = new Intl.DateTimeFormat(L.locale, { hour: '2-digit', minute: '2-digit' })
  t.time = (d) => timeFmt.format(d)
  const rel = new Intl.RelativeTimeFormat(L.locale, { numeric: 'auto' })
  t.ago = (ts, now = Date.now()) => {
    const s = Math.round((ts - now) / 1000)
    const a = Math.abs(s)
    if (a < 45) return rel.format(0, 'second')
    if (a < 3600) return rel.format(Math.round(s / 60), 'minute')
    if (a < 86400) return rel.format(Math.round(s / 3600), 'hour')
    return rel.format(Math.round(s / 86400), 'day')
  }
  return t
}
